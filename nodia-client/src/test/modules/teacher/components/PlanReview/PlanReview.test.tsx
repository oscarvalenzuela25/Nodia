import { fireEvent, render, screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { describe, expect, it, vi } from "vitest";
import PlanReview from "../../../../../modules/teacher/components/PlanReview";
import { planFixture } from "../../fixtures";

describe("Teacher plan assessment policy review", () => {
  it("preserves missing historical duration and empty structure until explicitly edited", async () => {
    const plan = structuredClone(planFixture);
    plan.outline = { ...plan.outline, title: "", organization: "days", day_count: null, sections: [] };
    const props = { plan, busy: false, futureRevision: true, canAccept: false, canAdjust: false, onSave: vi.fn(async () => {}), onAdjust: vi.fn(async () => {}), onAccept: vi.fn(async () => {}) };
    render(<PlanReview {...props} />);
    expect(screen.getByRole("heading", { name: plan.outline.topic })).toBeInTheDocument();
    expect(screen.queryByText(/jornadas de estudio$/)).not.toBeInTheDocument();
    expect(screen.getByText(/Esta propuesta aún no incluye secciones/)).toBeVisible();
    expect(screen.getByRole("button", { name: "Activar esta revisión" })).toBeDisabled();
    const user = userEvent.setup();
    await user.click(screen.getByRole("button", { name: "Editar estructura" }));
    const days = screen.getByRole("spinbutton", { name: "Cantidad de jornadas" });
    expect(days).toHaveValue(null);
    fireEvent.change(days, { target: { value: "5" } });
    await user.click(screen.getByRole("button", { name: "Volver al resumen" }));
    expect(screen.getByText("5 jornadas de estudio")).toBeInTheDocument();
    expect(props.onSave).not.toHaveBeenCalled();
    expect(props.onAccept).not.toHaveBeenCalled();
  });
  it("starts with a readable proposal and accepts it explicitly without requiring AI availability", async () => {
    const props = { plan: planFixture, busy: false, canAccept: true, canAdjust: false, onSave: vi.fn(async () => {}), onAdjust: vi.fn(async () => {}), onAccept: vi.fn(async () => {}) };
    render(<PlanReview {...props} />);
    expect(screen.getByRole("heading", { name: "Tu propuesta está lista" })).toBeInTheDocument();
    expect(screen.getByText("1 sección")).toBeInTheDocument();
    expect(screen.queryByRole("textbox")).not.toBeInTheDocument();
    const user = userEvent.setup();
    await user.click(screen.getByRole("button", { name: /DNS/ }));
    expect(screen.getAllByRole("listitem").find(item => item.textContent === "Explain resolution")).toBeVisible();
    expect(props.onSave).not.toHaveBeenCalled();
    expect(props.onAdjust).not.toHaveBeenCalled();
    expect(props.onAccept).not.toHaveBeenCalled();
    await user.click(screen.getByRole("button", { name: "Usar este plan" }));
    expect(props.onAccept).toHaveBeenCalledOnce();
    expect(props.onAdjust).not.toHaveBeenCalled();
    expect(props.onSave).not.toHaveBeenCalled();
  });
  it("saves real edited counts through the manual revision callback without asking Teacher or accepting the plan", async () => {
    const onSave = vi.fn(async () => {});
    const onAdjust = vi.fn(async () => {});
    const onAccept = vi.fn(async () => {});
    render(<PlanReview plan={planFixture} busy={false} canAccept canAdjust={false} onSave={onSave} onAdjust={onAdjust} onAccept={onAccept} />);
    const user = userEvent.setup();
    await user.click(screen.getByRole("button", { name: "Editar estructura" }));
    await user.click(screen.getByRole("button", { name: "Evaluación" }));
    const field = screen.getByRole("spinbutton", { name: "Práctica de unidad: selección única" });
    expect(field).toHaveValue(3);
    fireEvent.change(field, { target: { value: "4" } });
    await user.click(screen.getByRole("button", { name: "Guardar cambios" }));
    await waitFor(() => expect(onSave).toHaveBeenCalledOnce());
    expect(onSave).toHaveBeenCalledWith({ ...planFixture.outline, assessment_policy: { ...planFixture.outline.assessment_policy, practice_counts: { single_choice: 4, completion: 1, short_text: 1 } } });
    expect(onAdjust).not.toHaveBeenCalled();
    expect(onAccept).not.toHaveBeenCalled();
  });
  it("preserves an invalid count while busy/refetch changes and blocks save/accept until corrected", async () => {
    const props = { plan: planFixture, canAccept: true, canAdjust: true, onSave: vi.fn(async () => {}), onAdjust: vi.fn(async () => {}), onAccept: vi.fn(async () => {}) };
    const { rerender } = render(<PlanReview {...props} busy={false} />);
    const user = userEvent.setup();
    await user.click(screen.getByRole("button", { name: "Editar estructura" }));
    await user.click(screen.getByRole("button", { name: "Evaluación" }));
    const field = screen.getByRole("spinbutton", { name: "Final de sección: respuesta breve" });
    fireEvent.change(field, { target: { value: "" } });
    expect(screen.getByText(/Revisa las cantidades:/)).toBeInTheDocument();
    expect(screen.getByRole("button", { name: "Usar este plan" })).toBeDisabled();
    expect(screen.getByRole("button", { name: "Guardar cambios" })).toBeDisabled();
    await user.click(screen.getByRole("button", { name: "Volver al resumen" }));
    expect(screen.getByText(/Revisa las cantidades de Evaluación/)).toBeVisible();
    expect(screen.queryByRole("spinbutton", { name: "Final de sección: respuesta breve" })).not.toBeInTheDocument();
    await user.click(screen.getByRole("button", { name: "Pedir un ajuste" }));
    await user.type(screen.getByRole("textbox", { name: "Qué quieres ajustar" }), "Add an example");
    const adjust = screen.getByRole("button", { name: "Pedir un ajuste a Teacher" });
    expect(adjust).toBeDisabled();
    fireEvent.click(adjust);
    expect(props.onAdjust).not.toHaveBeenCalled();
    await user.click(screen.getByRole("button", { name: "Revisar cambios pendientes" }));
    expect(screen.getByRole("spinbutton", { name: "Final de sección: respuesta breve" })).toBe(field);
    rerender(<PlanReview {...props} busy />);
    expect(field).toBeDisabled();
    rerender(<PlanReview {...props} busy={false} />);
    expect(field).toHaveValue(null);
    fireEvent.change(field, { target: { value: "4" } });
    expect(adjust).toBeEnabled();
    expect(props.onSave).not.toHaveBeenCalled();
    expect(props.onAccept).not.toHaveBeenCalled();
  });
  it("preserves the adjustment draft and waits for the selected provider to be ready before requesting it", async () => {
    const props = { plan: planFixture, busy: false, canAccept: true, onSave: vi.fn(async () => {}), onAdjust: vi.fn(async () => {}), onAccept: vi.fn(async () => {}) };
    const { rerender } = render(<PlanReview {...props} canAdjust={false} />);
    const user = userEvent.setup();
    await user.click(screen.getByRole("button", { name: "Pedir un ajuste" }));
    const text = "Incluye un ejemplo de transferencia antes de la práctica.";
    const field = screen.getByRole("textbox", { name: "Qué quieres ajustar" });
    await user.type(field, text);
    const adjust = screen.getByRole("button", { name: "Pedir un ajuste a Teacher" });
    expect(adjust).toBeDisabled();
    fireEvent.click(adjust);
    expect(props.onAdjust).not.toHaveBeenCalled();
    await user.click(screen.getByRole("button", { name: "Pedir un ajuste" }));
    expect(field).not.toBeVisible();
    await user.click(screen.getByRole("button", { name: "Pedir un ajuste" }));
    expect(screen.getByRole("textbox", { name: "Qué quieres ajustar" })).toBe(field);
    rerender(<PlanReview {...props} canAdjust />);
    expect(field).toHaveValue(text);
    expect(adjust).toBeEnabled();
    await user.click(adjust);
    expect(props.onAdjust).toHaveBeenCalledExactlyOnceWith(text);
    expect(props.onSave).not.toHaveBeenCalled();
    expect(props.onAccept).not.toHaveBeenCalled();
  });
  it("retains edits through the overview, refetch and a resolved save callback without a replacement revision", async () => {
    const props = { plan: planFixture, canAccept: true, canAdjust: true, onSave: vi.fn(async () => {}), onAdjust: vi.fn(async () => {}), onAccept: vi.fn(async () => {}) };
    const { rerender } = render(<PlanReview {...props} busy={false} />);
    const user = userEvent.setup();
    await user.click(screen.getByRole("button", { name: "Editar estructura" }));
    const title = screen.getByRole("textbox", { name: "Título del plan de estudio (opcional)" });
    fireEvent.change(title, { target: { value: "My edited proposal" } });
    await user.click(screen.getByRole("button", { name: "Guardar cambios" }));
    expect(props.onSave).toHaveBeenCalledExactlyOnceWith({ ...planFixture.outline, title: "My edited proposal" });
    expect(title).toHaveValue("My edited proposal");
    await user.click(screen.getByRole("button", { name: "Volver al resumen" }));
    expect(screen.getByRole("heading", { name: "My edited proposal" })).toBeInTheDocument();
    expect(screen.getByRole("button", { name: "Usar este plan" })).toBeDisabled();
    rerender(<PlanReview {...props} plan={structuredClone(planFixture)} busy />);
    rerender(<PlanReview {...props} plan={structuredClone(planFixture)} busy={false} />);
    await user.click(screen.getByRole("button", { name: "Revisar cambios pendientes" }));
    expect(screen.getByRole("textbox", { name: "Título del plan de estudio (opcional)" })).toBe(title);
    expect(title).toHaveValue("My edited proposal");
    expect(props.onAccept).not.toHaveBeenCalled();
    expect(props.onAdjust).not.toHaveBeenCalled();
  });
});
